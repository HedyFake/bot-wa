// Jalankan setelah build, migrasi, dan seed pada database uji kosong.
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import { ScheduleDatabase } from '../dist/modules/schedule/database.js';
import { ScheduleService } from '../dist/modules/schedule/service.js';
import { parseSeed } from '../dist/database/seed-schema.js';
import { ReminderWorker } from '../dist/modules/reminders/worker.js';
import { OutboundGate } from '../dist/whatsapp/outbound/gate.js';
import { CommandDispatcher } from '../dist/admin/commands/dispatcher.js';
import { AdminAuthenticator } from '../dist/admin/authentication/authenticator.js';
import { ConfirmationManager } from '../dist/admin/authorization/confirmation.js';
import { GroupIntelligenceService } from '../dist/ai/classification/group-intelligence.js';
import { ModelRouter } from '../dist/ai/model-router/router.js';
import { loadConfig } from '../dist/config/env.js';
import { DeadlineNotifier } from '../dist/modules/academic/deadline-notices.js';
import { FunAndUtilityService } from '../dist/modules/fun/fun-utility-service.js';
import { MockWhatsAppProvider } from '../dist/whatsapp/adapters/mock.js';

const url = new URL(process.env.HDYBOT_TEST_DATABASE_URL || 'file:///missing');
if (!['localhost','127.0.0.1'].includes(url.hostname) || !/^\/hdybot_test_[a-z0-9_]+$/.test(url.pathname)) {
  throw Error('Gunakan HDYBOT_TEST_DATABASE_URL khusus PostgreSQL lokal bernama hdybot_test_<id>.');
}
const db = new PrismaClient({ datasourceUrl:url.href });
const seed = parseSeed(JSON.parse(readFileSync('data/class-5a.seed.json','utf8')));
const repo = new ScheduleDatabase(db,seed.class.name,seed);
const schedule = new ScheduleService(seed);
schedule.useDatabase(repo);
const actor = 'admin-uji';
const monday = seed.schedule_entries.find(s => s.weekday === 'MONDAY');
const code = monday.course_code;
try {
  await schedule.refresh();
  assert.equal(schedule.getForWeekday('MONDAY').length, seed.schedule_entries.filter(s=>s.weekday==='MONDAY').length);
  await assert.rejects(repo.preview('schedule.add','senin|11:30|11:45|' + code), /istirahat/);
  const entry = 'minggu|07:00|08:00|' + code + '|Lab Uji';
  const add = await repo.preview('schedule.add',entry);
  const backup = await repo.apply(add.change,actor);
  assert.ok(await db.botSetting.findUnique({where:{key:backup}}));
  await assert.rejects(repo.apply(add.change,actor), /berubah/);
  await assert.rejects(repo.preview('schedule.add',entry), /bertabrakan/);
  const change = await repo.preview('schedule.edit','minggu|07:00|minggu|07:30|08:30|' + code + '|Lab Baru');
  await repo.apply(change.change,actor);
  await schedule.refresh(true);
  assert.equal(schedule.getForWeekday('SUNDAY').find(s=>s.startTime==='07:30').room, 'Lab Baru');
  await repo.apply((await repo.preview('schedule.delete','minggu|07:30')).change,actor);
  const reset = await repo.preview('schedule.reset','');
  await repo.apply(reset.change,actor);
  assert.equal((await repo.read()).data.schedule_entries.length,seed.schedule_entries.length);
  const wa = new MockWhatsAppProvider();
  await wa.connect();
  const worker = () => new ReminderWorker(db,new OutboundGate({provider:wa,outboundEnabled:true,dryRun:false}),()=>[]);
  await worker().command('kelas@g.us','msg-uji','add','2026-11-09 08:00|Pengingat uji');
  const now = new Date('2026-11-09T01:00:00Z');
  await worker().pause(true);
  await worker().tick(now);
  assert.equal(wa.sent.length,0);
  await worker().pause(false);
  await Promise.all([worker().tick(now),worker().tick(now)]);
  await worker().tick(now);
  assert.equal(wa.sent.length,1);
  const deadlines=new FunAndUtilityService();
  const gate=new OutboundGate({provider:wa,outboundEnabled:true,dryRun:false});
  const migrate=()=>new ReminderWorker(db,gate,()=>[],deadlines);
  await db.reminder.create({data:{idempotencyKey:'legacy-deadline',targetJid:'kelas@g.us',text:'Deadline pendaftaran: 16 November 2026 pukul 14:00',fireAt:now}});
  await migrate().tick(now); await migrate().tick(now);
  assert.equal(deadlines.listAssignments().length,1);
  assert.equal(wa.sent.length,1);
  assert.equal((await db.reminder.findUnique({where:{idempotencyKey:'legacy-deadline'}})).status,'awaiting_owner');
  const notify=new DeadlineNotifier(deadlines,gate,'6280000000000@s.whatsapp.net');
  await notify.tick(now); await notify.tick(new Date('2026-11-13T07:00:00Z'));
  assert.deepEqual(wa.sent.slice(1).map(m=>m.chatJid),['6280000000000@s.whatsapp.net','6280000000000@s.whatsapp.net']);
  console.log('Lulus: deadline PostgreSQL masuk antrean sekali; notifikasi baru dan H−3 dikirim hanya ke owner mock.');
  const config = loadConfig({ OWNER_WHATSAPP:'6280000000000' });
  const owner = '6280000000000@s.whatsapp.net';
  const dispatcher = new CommandDispatcher({config, whatsapp:wa, outbound:new OutboundGate({provider:wa,outboundEnabled:true,dryRun:false}),
    auth:new AdminAuthenticator({ownerE164:config.OWNER_WHATSAPP,adminAllowlistE164:[]}), confirmations:new ConfirmationManager(),router:new ModelRouter(),schedule,scheduleDatabase:repo,intelligence:new GroupIntelligenceService(),startedAt:new Date()});
  let seq = 0;
  const cmd = (text, extra = {}) => dispatcher.handleInbound({chatJid:owner,senderJid:owner,chatType:'private',providerMessageId:'sched-'+(++seq),receivedAt:new Date(),text,...extra});
  assert.equal(await cmd('.resetjadwal',{chatType:'group',chatJid:'kelas@g.us'}),null);
  assert.match(await cmd('.resetjadwal',{chatJid:'628111111111@s.whatsapp.net',senderJid:'628111111111@s.whatsapp.net'}),/Akses ditolak/);
  const preview = await cmd('.tambahjadwal ' + entry);
  const nonce = preview.match(/\.confirm ([A-F0-9]+)/)[1];
  assert.ok(!(await repo.read()).data.schedule_entries.some(s=>s.weekday==='SUNDAY' && s.start_time==='07:00'));
  assert.match(await cmd('.confirm ' + nonce),/Perubahan jadwal tersimpan/);
  assert.match(await cmd('.jadwal minggu'),/Lab Uji/);
  assert.match(await cmd('.cekjadwal 2026-11-15'),/Lab Uji/);
  assert.match(await cmd('.confirm ' + nonce),/replayed/);
  const original = await repo.preview('schedule.delete','senin|' + monday.start_time);
  await repo.apply(original.change,owner);
  execFileSync(process.execPath,['node_modules/tsx/dist/cli.mjs','prisma/seed.ts'],{env:{...process.env,DATABASE_URL:url.href,DOTENV_CONFIG_PATH:'unused-mock-test.env'},stdio:'pipe',timeout:30000});
  assert.ok(!(await repo.read()).data.schedule_entries.some(s=>s.weekday==='MONDAY' && s.start_time === monday.start_time));
  await repo.apply((await repo.preview('schedule.reset','')).change,owner);
  console.log('Lulus: konfirmasi owner, akses grup, anti-replay dan seed ulang mempertahankan keputusan admin.');
  console.log('Lulus: baca, pratinjau, konflik, tambah, edit, hapus, reset, backup, serta pemulihan dan klaim pengingat dengan PostgreSQL.');
} finally {
  await db.$disconnect();
}
